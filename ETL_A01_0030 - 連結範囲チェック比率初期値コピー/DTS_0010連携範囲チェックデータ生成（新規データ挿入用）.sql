    FROM
        CONS_SCO_CHK_SCE_OWNER_RATE
    LEFT JOIN
        CONS_SCO_CHK_EXISTING
    ON
        CONS_SCO_CHK_SCE_OWNER_RATE.COD_SCENARIO = CONS_SCO_CHK_EXISTING.COD_SCENARIO
        AND CONS_SCO_CHK_SCE_OWNER_RATE.COD_PERIODO = CONS_SCO_CHK_EXISTING.COD_PERIODO
        AND CONS_SCO_CHK_SCE_OWNER_RATE.COD_SCENARIO_AW = CONS_SCO_CHK_EXISTING.COD_SCENARIO_AW
        AND CONS_SCO_CHK_SCE_OWNER_RATE.COD_AZIENDA = CONS_SCO_CHK_EXISTING.COD_AZIENDA
        AND CONS_SCO_CHK_SCE_OWNER_RATE.COD_AZI_CTP = CONS_SCO_CHK_EXISTING.COD_AZI_CTP
)

