        CONS_SCO_CHK_SCE_OWNER_RATE.TEXT_005,
        CONS_SCO_CHK_SCE_OWNER_RATE.TEXT_006,
        CONS_SCO_CHK_SCE_OWNER_RATE.TEXT_007,
        CONS_SCO_CHK_SCE_OWNER_RATE.TEXT_008,
        CONS_SCO_CHK_SCE_OWNER_RATE.TEXT_009,
