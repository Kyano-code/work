        CONS_SCO_CHK_SCE_OWNER_RATE.COD_AZI_CTP,
        CONS_SCO_CHK_SCE_OWNER_RATE.COD_CATEGORIA,
        CONS_SCO_CHK_SCE_OWNER_RATE.COD_DEST3,
        CONS_SCO_CHK_SCE_OWNER_RATE.COD_DEST4,
