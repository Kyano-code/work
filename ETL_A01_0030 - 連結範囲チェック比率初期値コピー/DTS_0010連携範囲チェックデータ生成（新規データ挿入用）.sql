        CONS_SCO_CHK_SCE_OWNER_RATE.COD_SCENARIO_AW,
        CONS_SCO_CHK_SCE_OWNER_RATE.INT_001,
        CONS_SCO_CHK_SCE_OWNER_RATE.INT_002,
        CONS_SCO_CHK_SCE_OWNER_RATE.INT_003,
